/**
 * Helper to retrieve a course by ID or primary skill name
 */
export function getCourseForSkill(skillName: string): LearningCourse | undefined {
  const normalized = skillName.trim().toLowerCase();
  
  // Exact match
  const exact = COURSE_CATALOG.find(
    (c) => c.primarySkill.toLowerCase() === normalized || c.skills.some((s) => s.toLowerCase() === normalized)
  );
  if (exact) return exact;

  // Fuzzy match keywords
  if (normalized.includes("sql") || normalized.includes("postgres") || normalized.includes("database")) {
    return COURSE_CATALOG.find((c) => c.id === "nptel-dbms-sql");
  }
  if (normalized.includes("react") || normalized.includes("frontend") || normalized.includes("next")) {
    return COURSE_CATALOG.find((c) => c.id === "harvard-react-web");
  }
  if (normalized.includes("node") || normalized.includes("express") || normalized.includes("backend") || normalized.includes("api")) {
    return COURSE_CATALOG.find((c) => c.id === "fcc-nodejs-backend");
  }
  if (normalized.includes("docker") || normalized.includes("kubernetes") || normalized.includes("devops") || normalized.includes("cloud")) {
    return COURSE_CATALOG.find((c) => c.id === "fcc-docker-k8s");
  }
  if (normalized.includes("python") || normalized.includes("machine learning") || normalized.includes("data") || normalized.includes("bi")) {
    return COURSE_CATALOG.find((c) => c.id === "nptel-python-ds");
  }
  if (normalized.includes("security") || normalized.includes("soc") || normalized.includes("cyber") || normalized.includes("appsec")) {
    return COURSE_CATALOG.find((c) => c.id === "cs50-cybersecurity");
  }
  if (normalized.includes("embedded") || normalized.includes("iot") || normalized.includes("hardware") || normalized.includes("microcontroller")) {
    return COURSE_CATALOG.find((c) => c.id === "nptel-embedded-iot");
  }
  if (normalized.includes("system design") || normalized.includes("distributed") || normalized.includes("architect")) {
    return COURSE_CATALOG.find((c) => c.id === "mit-system-design");
  }
  if (normalized.includes("html") || normalized.includes("css") || normalized.includes("web design") || normalized.includes("javascript")) {
    return COURSE_CATALOG.find((c) => c.id === "fcc-web-foundations");
  }
  if (normalized.includes("linux") || normalized.includes("operating system") || normalized.includes("sre") || normalized.includes("bash")) {
    return COURSE_CATALOG.find((c) => c.id === "nptel-linux-os");
  }

  return COURSE_CATALOG[0]; // Safe fallback to DBMS / SQL
}

